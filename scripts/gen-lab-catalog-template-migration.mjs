/**
 * Reads supabase/seeds/lab_catalog_template_manifest.json and writes
 * supabase/migrations/<timestamp>_lab_catalog_results_templates.sql
 *
 * Deterministic UUIDs per test code (SHA-256 derived v4-like UUID).
 */
import crypto from "crypto";
import fs from "fs";
import path from "path";

const root = process.cwd();
const manifestPath = path.join(root, "supabase", "seeds", "lab_catalog_template_manifest.json");
const outDir = path.join(root, "supabase", "migrations");
const outFile = path.join(outDir, "20260510140000_lab_catalog_results_templates.sql");

function uuidFromCode(code) {
  const hash = crypto.createHash("sha256").update(`lifehub:lab_test:${code}`).digest();
  const buf = Buffer.alloc(16);
  hash.copy(buf, 0, 0, 16);
  buf[6] = (buf[6] & 0x0f) | 0x40;
  buf[8] = (buf[8] & 0x3f) | 0x80;
  const h = buf.toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}

function escSql(s) {
  if (s == null || s === "") return "NULL";
  return `'${String(s).replace(/'/g, "''")}'`;
}

function escBool(b) {
  return b === true ? "true" : "false";
}

const raw = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const tests = raw.tests;
if (!Array.isArray(tests) || tests.length === 0) {
  console.error("No tests in manifest");
  process.exit(1);
}

const valueRows = tests.map((t) => {
  const id = uuidFromCode(t.code);
  const cat = Number(t.category_id);
  const ref = t.reference_range != null && String(t.reference_range).trim() === "" ? null : t.reference_range;
  const tpl = t.results_template_code == null || String(t.results_template_code).trim() === "" ? null : String(t.results_template_code).trim();
  const unit = t.unit != null && String(t.unit).trim() === "" ? null : t.unit;
  const st = t.specimen_type != null && String(t.specimen_type).trim() === "" ? null : t.specimen_type;
  const price = t.price == null ? 0 : Number(t.price);
  const priceSql = Number.isFinite(price) ? price.toFixed(2) : "0";
  return (
    "(" +
    [
      escSql(id),
      String(cat),
      escSql(t.code),
      escSql(t.name),
      escSql(t.description ?? null),
      st == null ? "NULL" : escSql(st),
      unit == null ? "NULL" : escSql(unit),
      ref == null ? "NULL" : escSql(ref),
      "NULL",
      priceSql,
      escBool(!!t.requires_fasting),
      String(t.sort_order ?? 0),
      "true",
      tpl == null ? "NULL" : escSql(tpl),
    ].join(", ") +
    ")"
  );
});

const preamble = `-- Lab catalog aligned to templates/Lab Results/LIFEHUB-MEDICAL-Results-*.pdf
-- Generated by scripts/gen-lab-catalog-template-migration.mjs from supabase/seeds/lab_catalog_template_manifest.json

alter table public.lab_tests add column if not exists results_template_code text;
comment on column public.lab_tests.results_template_code is 'Key for blank results PDF under templates/Lab Results/: LIFEHUB-MEDICAL-Results-<KEY>.pdf (BLOODCHEM1..11, HEMA, URINALYSIS, ART).';

alter table public.lab_tests add column if not exists reference_range text;

-- Repurpose fixed category ids (see scripts/write-lab-migration.mjs): 2=ART, 6=URINALYSIS; retire 3,4,7 from modal.
update public.lab_categories
set code = 'ART',
    name = 'Arterial blood gas',
    description = 'ABG — LIFEHUB-MEDICAL-Results-ART.pdf',
    sort_order = 4,
    is_active = true
where id = 2;

update public.lab_categories
set is_active = false,
    sort_order = coalesce(sort_order, 0) + 80
where id in (3, 4, 7);

update public.lab_categories
set code = 'URINALYSIS',
    name = 'Urinalysis',
    description = 'LIFEHUB-MEDICAL-Results-URINALYSIS.pdf',
    sort_order = 3,
    is_active = true
where id = 6;

update public.lab_categories
set sort_order = 1,
    is_active = true
where id = 1;

update public.lab_categories
set sort_order = 2,
    is_active = true,
    description = 'Blood chemistry panels (BLOODCHEM1–11 result forms)'
where id = 5;

update public.lab_categories
set sort_order = 5,
    is_active = true
where id = 8;

`;

const insertBlock = `
insert into public.lab_tests (
  id,
  category_id,
  code,
  name,
  description,
  specimen_type,
  unit,
  reference_range,
  turnaround_hours,
  price,
  requires_fasting,
  sort_order,
  is_active,
  results_template_code
) values
${valueRows.join(",\n")}
on conflict (code) do update set
  category_id = excluded.category_id,
  name = excluded.name,
  description = excluded.description,
  specimen_type = excluded.specimen_type,
  unit = excluded.unit,
  reference_range = excluded.reference_range,
  turnaround_hours = excluded.turnaround_hours,
  price = excluded.price,
  requires_fasting = excluded.requires_fasting,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active,
  results_template_code = excluded.results_template_code;

`;

const postamble = `
do $$
declare
  vseq text := pg_get_serial_sequence('public.lab_categories', 'id');
begin
  if vseq is not null then
    execute format(
      'select setval(%L, coalesce((select max(id) from public.lab_categories), 1))',
      vseq
    );
  end if;
end $$;
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, preamble + insertBlock + postamble, "utf8");
console.log("Wrote", outFile, "(" + tests.length + " tests)");
