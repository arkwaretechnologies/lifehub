/** @type {Array<[string, object]>} */
const pairs = [];

function layoutRow(code, layout) {
  const rounded = {
    ...layout,
    refFromTop: Math.round(layout.refFromTop * 10) / 10,
    refX: Math.round(layout.refX * 10) / 10,
  };
  pairs.push([code, rounded]);
}

for (let i = 0; i < HEMA_PRINT_CODES.length; i++) {
  layoutRow(HEMA_PRINT_CODES[i], {
    refX: HEMA_REF_X,
    refFromTop: HEMA_FIRST + i * HEMA_STEP,
    fontSize: 9,
    maxWidth: 120,
    pageIndex: 0,
  });
}

function addSequential(codes, cfg) {
  for (let i = 0; i < codes.length; i++) {
    layoutRow(codes[i], {
      refX: cfg.refX,
      refFromTop: cfg.firstFromTop + i * cfg.rowStep,
      fontSize: cfg.fontSize,
      maxWidth: cfg.maxWidth,
      pageIndex: cfg.pageIndex ?? 0,
    });
  }
}

